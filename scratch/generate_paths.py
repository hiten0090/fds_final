# Script to generate SVG continent paths for an 800x400 equirectangular world map
# Equirectangular projection:
# x = (lng + 180) / 360 * 800
# y = (90 - lat) / 180 * 400

def pt(lng, lat):
    x = round((lng + 180) / 360 * 800, 1)
    y = round((90 - lat) / 180 * 400, 1)
    return f"{x},{y}"

def make_path(points):
    res = []
    for i, p in enumerate(points):
        coord = pt(p[0], p[1])
        if i == 0:
            res.append(f"M {coord}")
        else:
            res.append(f"L {coord}")
    res.append("Z")
    return " ".join(res)

